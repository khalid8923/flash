/* ═══════════════════════════════════════════════════════════
   Catalog — Migration Script
   Generates game config files from: DB + atlas.ts + prompts.ts + _meta.ts
   Run: npx tsx src/catalog/_migrate.ts
   ═══════════════════════════════════════════════════════════ */

import { ATLAS } from '../services/difficulty/atlas.js';
import { PROMPTS } from '../services/ai/prompts.js';
import { pool } from '../config/db.js';
import { writeFileSync, existsSync, mkdirSync, rmSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { GAME_META } from './_meta.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT_DIR = join(__dirname, 'games');

interface DbGameRow {
  id: string;
  name: string;
  domain_id: string;
  trial_pattern: string;
  primary_metric: string;
  metric_direction: string;
  rt_floor_ms: number;
  rt_ceiling_ms: number;
  max_trials_per_session: number;
  min_duration_ms: number;
  max_duration_ms: number;
  max_score: number;
  trial_exclusion_rules: unknown;
  game_version: string;
  scoring_version: number;
  status: string;
}

interface AtlasLevel {
  level: number;
  label: string;
  levers: Record<string, number | string | boolean>;
  calibrated_difficulty: number;
  domain_loadings: Record<string, number>;
}

/* ─── Helpers ─── */
function toCamelCase(s: string): string {
  return s.replace(/-([a-z])/g, (_, c: string) => c.toUpperCase());
}

function esc(s: string): string {
  return JSON.stringify(s);
}

function serializeLevel(l: AtlasLevel, indent: string): string {
  const leversJson = JSON.stringify(l.levers);
  return `${indent}{ level: ${l.level}, label: ${esc(l.label)}, levers: ${leversJson}, calibrated_difficulty: ${l.calibrated_difficulty} }`;
}

/* Defensive defaults — used if DB has NULL (should not happen after migration 011) */
const DEFAULTS = {
  rt_floor_ms: 100,
  rt_ceiling_ms: 60000,
  max_trials_per_session: 200,
  min_duration_ms: 30000,
  max_duration_ms: 3600000,
  max_score: 100000,
};

function numOr(value: number | null | undefined, fallback: number): number {
  if (typeof value === 'number' && Number.isFinite(value)) return value;
  return fallback;
}

function serializeConfig(
  db: DbGameRow,
  meta: typeof GAME_META[string],
  atlasLevels: AtlasLevel[]
): string {
  const exportName = toCamelCase(db.id) + 'Config';
  const prompt = PROMPTS[db.id];
  const domainWeights = atlasLevels[0]?.domain_loadings ?? {};

  /* Apply defensive defaults */
  const rtFloor = numOr(db.rt_floor_ms, DEFAULTS.rt_floor_ms);
  const rtCeiling = numOr(db.rt_ceiling_ms, DEFAULTS.rt_ceiling_ms);
  const maxTrials = numOr(db.max_trials_per_session, DEFAULTS.max_trials_per_session);
  const minDuration = numOr(db.min_duration_ms, DEFAULTS.min_duration_ms);
  const maxDuration = numOr(db.max_duration_ms, DEFAULTS.max_duration_ms);
  const maxScore = numOr(db.max_score, DEFAULTS.max_score);

  /* Sanity: rt_ceiling must be > rt_floor */
  const safeRtCeiling = rtCeiling > rtFloor ? rtCeiling : DEFAULTS.rt_ceiling_ms;

  const levelsBlock = atlasLevels
    .map((l) => serializeLevel(l, '    '))
    .join(',\n');

  const promptBlock = prompt
    ? `
  ai_prompt: {
    system: ${esc(prompt.system)},
    schema: ${esc(prompt.schema)},
    build: ${prompt.build.toString()},
  },
`
    : '';

  const exclusionRules = Array.isArray(db.trial_exclusion_rules)
    ? JSON.stringify(db.trial_exclusion_rules)
    : '[]';

  return `/* ═══════════════════════════════════════════════════════════
   Game: ${db.name}
   Domain: ${db.domain_id}
   AUTO-GENERATED by catalog/_migrate.ts — do not edit by hand
   ═══════════════════════════════════════════════════════════ */

import type { GameConfig } from '../types.js';

export const ${exportName}: GameConfig = {
  id: ${esc(db.id)},
  name: {
    en: ${esc(db.name)},
    ar: ${esc(meta.nameAr)},
  },
  domain: ${esc(db.domain_id)} as GameConfig['domain'],
  icon: ${esc(meta.icon)},
  description: {
    en: ${esc(meta.descEn)},
    ar: ${esc(meta.descAr)},
  },

  trial_pattern: ${esc(db.trial_pattern)} as GameConfig['trial_pattern'],
  primary_metric: ${esc(db.primary_metric)},
  metric_direction: ${esc(db.metric_direction)} as GameConfig['metric_direction'],
  rt_floor_ms: ${rtFloor},
  rt_ceiling_ms: ${safeRtCeiling},
  max_trials_per_session: ${maxTrials},
  min_duration_ms: ${minDuration},
  max_duration_ms: ${maxDuration},
  max_score: ${maxScore},
  trial_exclusion_rules: ${exclusionRules},

  game_version: ${esc(db.game_version)},
  scoring_version: ${db.scoring_version},
  status: ${esc(db.status)} as GameConfig['status'],

  domain_weights: ${JSON.stringify(domainWeights)},

  levels: [
${levelsBlock},
  ],
${promptBlock}
  citation: ${esc(meta.citation)},
  seed_schema: ${esc(meta.seedSchema)},
};
`;
}

/* ─── Main ─── */
async function main() {
  const cleanup = process.argv.includes('--clean');

  if (!existsSync(OUT_DIR)) mkdirSync(OUT_DIR, { recursive: true });

  if (cleanup) {
    console.log('--clean flag detected. Removing existing generated files...');
    const { readdirSync } = await import('node:fs');
    for (const f of readdirSync(OUT_DIR)) {
      if (f.endsWith('.ts')) {
        rmSync(join(OUT_DIR, f));
      }
    }
  }

  const dbRes = await pool.query<DbGameRow>(
    `SELECT id, name, domain_id, trial_pattern, primary_metric, metric_direction,
            rt_floor_ms, rt_ceiling_ms, max_trials_per_session,
            min_duration_ms, max_duration_ms, max_score,
            trial_exclusion_rules, game_version, scoring_version, status
       FROM games
      WHERE deleted_at IS NULL
      ORDER BY domain_id, id`
  );
  const gamesById = new Map(dbRes.rows.map((r) => [r.id, r]));

  let generated = 0;
  let skippedNoMeta = 0;
  let skippedNoDb = 0;

  for (const atlas of ATLAS) {
    const id = atlas.game_id;
    const db = gamesById.get(id);
    const meta = GAME_META[id];

    if (!db) {
      console.warn(`SKIP ${id}: no DB row`);
      skippedNoDb++;
      continue;
    }
    if (!meta) {
      console.warn(`SKIP ${id}: no META entry (add to _meta.ts)`);
      skippedNoMeta++;
      continue;
    }

    const source = serializeConfig(db, meta, atlas.levels as AtlasLevel[]);
    const outPath = join(OUT_DIR, `${id}.ts`);
    writeFileSync(outPath, source, 'utf-8');
    console.log(`OK ${id}.ts`);
    generated++;
  }

  console.log(`\n─────────────────────────────────────`);
  console.log(`Generated: ${generated}`);
  console.log(`Skipped (no META): ${skippedNoMeta}`);
  console.log(`Skipped (no DB):   ${skippedNoDb}`);
  console.log(`Total in ATLAS:    ${ATLAS.length}`);
  console.log(`─────────────────────────────────────`);
  process.exit(0);
}

main().catch((err) => {
  console.error('Migration failed:', err);
  process.exit(1);
});